export interface Character {
  profession: string;
  biology: string;
  health: string;
  hobby: string;
  phobia: string;
  baggage: string;
  specialInfo: string;
  action: string;
}

export function getRandomItem<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateCharacter(): Character {
  return {
    profession: getRandomItem(professions),
    biology: getRandomItem(biology),
    health: getRandomItem(health),
    hobby: getRandomItem(hobbies),
    phobia: getRandomItem(phobias),
    baggage: getRandomItem(baggage),
    specialInfo: getRandomItem(specialInfo),
    action: getRandomItem(actions),
  };
}
